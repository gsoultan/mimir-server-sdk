"""Writes python/src/mimirsdk/types.py, which re-exports every message and
enum of the server's API under the server's own names. Run by gen.sh."""

import importlib
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent / "python" / "src"
sys.path.insert(0, str(root))

from google.protobuf.descriptor import EnumDescriptor  # noqa: E402

gen = root / "mimirsdk" / "_gen" / "mimir" / "v1"
lines = [
    '"""Every message and enum of mimir-server\'s API, under the names the',
    "server gives them. See the server's proto files (proto/mimir/v1) for",
    'what each field means. Generated by scripts/gen.sh; do not edit."""',
    "",
]
exported = []
for path in sorted(gen.glob("*_pb2.py")):
    mod_name = f"mimirsdk._gen.mimir.v1.{path.stem}"
    mod = importlib.import_module(mod_name)
    fd = mod.DESCRIPTOR
    names = list(fd.message_types_by_name) + list(fd.enum_types_by_name)
    for enum in fd.enum_types_by_name.values():
        assert isinstance(enum, EnumDescriptor)
        names += [v.name for v in enum.values]
    if not names:
        continue
    lines.append(f"from ._gen.mimir.v1.{path.stem} import (")
    for n in names:
        lines.append(f"    {n} as {n},")
    lines.append(")")
    exported += names
lines += ["", "__all__ = ["]
lines += [f'    "{n}",' for n in exported]
lines += ["]", ""]
(root / "mimirsdk" / "types.py").write_text("\n".join(lines))
print(f"types.py: {len(exported)} names")
